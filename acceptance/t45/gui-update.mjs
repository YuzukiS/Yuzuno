import { chromium } from "../../web/node_modules/playwright-core/index.mjs";
import { readFileSync, writeFileSync } from "node:fs";
import assert from "node:assert/strict";

const statePath = "target/t45/lab/state.json";
const state = JSON.parse(readFileSync(statePath));
assert.ok(state.createOperationId && state.number, "Finish native creation first");
assert.ok(!state.updateOperationId, "Inspect existing update before repeating acceptance");
const base = "http://127.0.0.1:4477";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox", "--disable-dev-shm-usage"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const request = async (path, body) => {
  const response = await page.request.post(base + "/api" + path, { headers: { "X-Yuzuno-Client": "desktop" }, data: body });
  assert.ok(response.ok(), await response.text());
  return response.json();
};
try {
  await page.goto(base);
  await page.getByRole("button", { name: "Tasks & messages", exact: false }).click();
  await page.locator(`button[data-task-id="${state.taskId}"]`).click();
  const panel = page.getByRole("region", { name: "PR operations", exact: true });
  await panel.getByText("Operation ID: " + state.createOperationId, { exact: true }).waitFor();
  const body = readFileSync("target/t45/lab/pr-body.md", "utf8") + `\n\nNative acceptance created this delivery through operation \`${state.createOperationId}\`. The author Turn ended before the remote write; Core reconciled a deliberately lost successful reply and retained the same PR and task link. This body update is submitted from the task GUI.\n`;
  await panel.getByLabel("Action", { exact: true }).selectOption("update");
  await panel.getByLabel("PR repository", { exact: true }).selectOption(String(state.repositoryId));
  await panel.getByLabel("Base branch", { exact: true }).fill("main");
  await panel.getByLabel("Head branch", { exact: true }).fill("feat/t45-pr-operations");
  await panel.getByLabel("PR number", { exact: false }).fill(String(state.number));
  await panel.getByLabel("PR title", { exact: true }).fill("feat: durable PR creation and updates from tasks");
  await panel.getByLabel("PR body", { exact: true }).fill(body);
  await panel.getByLabel("PR result recipient", { exact: true }).selectOption(state.agentId);
  const accepted = page.waitForResponse(r => r.url() === base + "/api/pr-operations" && r.request().method() === "POST");
  await panel.getByRole("button", { name: "Update PR", exact: true }).click();
  const response = await accepted;
  assert.ok(response.ok(), await response.text());
  const run = await response.json(), payload = response.request().postDataJSON();
  state.updateOperationId = run.id;
  writeFileSync(statePath, JSON.stringify(state, null, 2));
  assert.ok(!("draft" in payload));
  assert.equal(run.notificationRecipient.id, state.agentId);
  assert.equal((await request("/pr-operations", payload)).id, run.id);
  const row = panel.locator(`[data-operation-id="${run.id}"]`);
  await row.getByText("Completed", { exact: true }).waitFor({ timeout: 45000 });
  const result = await request("/collaboration/github_pr_get", { taskId: state.taskId, operationId: run.id });
  assert.equal(result.remote.number, state.number); assert.equal(result.remote.body, body);
  assert.equal(result.remote.draft, false); assert.equal(result.linked, true); assert.equal(result.outcome, "updated");
  const reused = await request("/pr-operations", { ...payload, requestId: "t45-gui-reuse-existing-v1", action: "create", draft: true, number: undefined, title: "This reuse must preserve the actual PR title", notifyAgentId: null });
  const reusedRow = panel.locator(`[data-operation-id="${reused.id}"]`);
  await reusedRow.getByText("Completed", { exact: true }).waitFor({ timeout: 45000 });
  const reuseResult = await request("/collaboration/github_pr_get", { taskId: state.taskId, operationId: reused.id });
  assert.equal(reuseResult.outcome, "reused"); assert.equal(reuseResult.remote.number, state.number);
  assert.equal(reuseResult.remote.title, payload.title); assert.equal(reuseResult.remote.draft, false);
  await row.getByText("Submitted content and recovery history", { exact: true }).click();
  await row.getByText("Last observed PR body", { exact: true }).waitFor();
  await row.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "target/t45/gui-update.png", fullPage: true });
  const task = await request("/collaboration/task_get", { taskId: state.taskId, limit: 1 });
  assert.equal(task.task.status, "todo"); assert.ok(task.task.github.some(link => link.number === state.number));
  const mail = await request("/collaboration/peer_read", { agentId: state.agentId, priority: "normal", limit: 100 });
  const notices = mail.messages.filter(m => m.operationId === run.id);
  assert.equal(notices.length, 1); assert.equal(notices[0].sender.kind, "system");
  assert.deepEqual(errors, []);
  writeFileSync("target/t45/gui-update.json", JSON.stringify({ result, reuseResult, task: task.task, notification: notices[0], errors }, null, 2));
  console.log(JSON.stringify({ operationId: run.id, number: state.number, outcome: result.outcome, linked: result.linked, reuseOperationId: reused.id, notifications: notices.length, errors }));
} catch (error) {
  await page.screenshot({ path: "target/t45/gui-failure.png", fullPage: true });
  writeFileSync("target/t45/gui-failure.txt", await page.locator("body").innerText());
  throw error;
} finally { await browser.close(); }
