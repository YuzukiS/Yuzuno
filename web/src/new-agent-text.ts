/** "5 min ago": when a Claude session was saved, coarse on purpose. */
export function savedAgoIn(language: Language, at: number | null, now = Date.now()) {
  const zh = language === "zh-Hans";
  if (!at) return zh ? "时间未知" : "at an unknown time";
  const seconds = Math.max(0, Math.round((now - at) / 1000));
  if (seconds < 45) return zh ? "刚刚" : "just now";
  if (seconds < 3600) {
    const minutes = Math.max(1, Math.round(seconds / 60));
    return zh ? `${minutes} 分钟前` : `${minutes} min ago`;
  }
  if (seconds < 86400) return zh ? `${Math.round(seconds / 3600)} 小时前` : `${Math.round(seconds / 3600)} h ago`;
  return zh ? `${Math.round(seconds / 86400)} 天前` : `${Math.round(seconds / 86400)} d ago`;
}
