// A time limit as people say it: whole hours, else minutes, else seconds.
const span = (seconds: number) => seconds % 3600 === 0 ? `${seconds / 3600} ${seconds === 3600 ? "hour" : "hours"}`
  : seconds % 60 === 0 ? `${seconds / 60} minutes` : `${seconds} seconds`;
const spanZh = (seconds: number) => seconds % 3600 === 0 ? `${seconds / 3600} 小时` : seconds % 60 === 0 ? `${seconds / 60} 分钟` : `${seconds} 秒`;
// Delays one after another: "30 seconds, 2 minutes and 10 minutes".
const spans = (delays: number[]) => delays.length < 2 ? delays.map(span).join("")
  : `${delays.slice(0, -1).map(span).join(", ")} and ${span(delays[delays.length - 1])}`;
const spansZh = (delays: number[]) => delays.map(spanZh).join("、");
const times = (n: number) => n === 1 ? "once" : `${n} times`;

