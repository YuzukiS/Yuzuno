// The generated validator Core runs (T-37): the committed contract matches
// its source, validator.mjs is generated rather than committed (YN-22), and the
// bundle works on its own, away from this checkout.
import test, { after } from "node:test";
import assert from "node:assert/strict";
import { execFileSync, spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";
import { COMMITTED, generate, outputDir, validatorHeader } from "./result-validator.mjs";
import { parseContract } from "./contract-json.mjs";
import { describeContract, SCHEMA_VERSION } from "../src/intelligent-ui/contract.ts";
import { comparisonExample } from "../src/intelligent-ui/examples.ts";

const committed = (name) => readFile(new URL(name, outputDir), "utf8");
let cache;
const files = async () => (cache ??= await generate());

let dir;
after(() => dir && rm(dir, { recursive: true, force: true }));
/** A freshly generated validator.mjs in a folder of its own, away from this checkout. */
async function bundle() {
  dir ??= await mkdtemp(join(tmpdir(), "result-validator-"));
  const path = join(dir, "validator.mjs");
  await writeFile(path, (await files())["validator.mjs"]);
  return path;
}

test("the committed contract and notices are what the contract generates", async () => {
  const generated = await files();
  for (const name of COMMITTED)
    assert.equal(await committed(name), generated[name], `runtimes/result-validator/${name} is stale: npm run build:result-validator`);
  // The Project Brief's part (T-85) is checked by brief-contract.test.mjs.
  const { brief, ...described } = parseContract(generated["contract.json"]);
  assert.deepEqual(described, JSON.parse(JSON.stringify(describeContract())));
  assert.equal(typeof brief?.guide, "string");
});

test("contract.json keeps every line of a text on a line of its own, so different lines merge (YN-22)", async () => {
  const strings = [];
  const walk = (value) => (typeof value === "string" ? strings.push(value) : value && typeof value === "object" && Object.values(value).forEach(walk));
  const raw = JSON.parse((await files())["contract.json"]);
  walk(raw);
  assert.deepEqual(strings.filter((text) => text.includes("\n")), [], "no text of several lines is written as one string");
  assert.ok(raw.brief.guide.$lines.length > 100 && raw.fenceGuide.$lines.length > 5, "the guides are split into lines");
});

test("validator.mjs is generated, never committed, and names the contract it was generated with", async () => {
  const generated = await files();
  const [first, header, ...body] = generated["validator.mjs"].split("\n");
  assert.match(first, /^\/\/ Generated by web\/tools\/result-validator\.mjs/);
  assert.match(header, /^\/\/ yuzuno-result-validator contract=[0-9a-f]{64} body=[0-9a-f]{64}$/);
  assert.equal(header, validatorHeader(generated["contract.json"], body.join("\n")));
  assert.equal(header.slice(header.indexOf("contract=") + 9, header.indexOf(" body=")),
    createHash("sha256").update(await committed("contract.json")).digest("hex"));
  const tracked = execFileSync("git", ["ls-files", "--", "."], { cwd: fileURLToPath(outputDir), encoding: "utf8" });
  assert.deepEqual(tracked.split("\n").filter(Boolean).sort(), ["THIRD_PARTY_NOTICES.txt", "contract.json"]);
});

test("the bundle runs alone, outside this checkout, and answers in order", async () => {
  const path = await bundle();
  const child = spawn(process.execPath, ["validator.mjs"], { cwd: dirname(path), env: {}, stdio: ["pipe", "pipe", "inherit"] });
  const answers = createInterface({ input: child.stdout })[Symbol.asyncIterator]();
  const ask = async (line) => {
    child.stdin.write(`${line}\n`);
    return JSON.parse((await answers.next()).value);
  };
  const untitled = structuredClone(comparisonExample);
  delete untitled.elements.options.props.title;
  const accepted = await ask(JSON.stringify({ id: 1, spec: untitled }));
  assert.equal(accepted.id, 1);
  assert.equal(accepted.ok, true);
  assert.equal(accepted.schemaVersion, SCHEMA_VERSION);
  assert.equal(accepted.spec.elements.options.props.title, "Table");
  assert.deepEqual(accepted.defaults, ["elements.options.props.title"]);
  const rejected = await ask(JSON.stringify({ id: 2, spec: { root: "r", elements: { r: { type: "Html", props: {} } } } }));
  assert.deepEqual(rejected, {
    id: 2, ok: false, schemaVersion: SCHEMA_VERSION,
    problems: [{ code: "unknown_component", reason: "Unknown or unsupported component type.", path: "elements.r.type" }],
  });
  assert.equal((await ask(JSON.stringify({ id: 3 }))).ok, false, "a missing spec is the Agent's problem");
  assert.deepEqual(await ask("not json"), { id: null, error: "unreadable request" });
  child.stdin.end();
  assert.equal(await new Promise((resolve) => child.on("exit", resolve)), 0, "exits when Core closes its input");
});

test("the bundle accepts a Brief section it can repair, says how, and refuses one it cannot as sent (YN-14)", async () => {
  const child = spawn(process.execPath, [await bundle()], { env: {}, stdio: ["pipe", "pipe", "inherit"] });
  const answers = createInterface({ input: child.stdout })[Symbol.asyncIterator]();
  const ask = async (request) => {
    child.stdin.write(`${JSON.stringify(request)}\n`);
    return JSON.parse((await answers.next()).value);
  };
  const section = (elements) => ({ key: "demo", kind: "report", title: "Demo",
    body: { root: "body", elements: { body: { type: "BriefBody", props: {}, children: Object.keys(elements) }, ...elements } } });
  const repaired = await ask({ id: 1, op: "briefSection", section: section({ log: { type: "Code", props: { code: "FAIL x" } } }) });
  assert.equal(repaired.ok, true, JSON.stringify(repaired));
  assert.deepEqual(repaired.normalized.body.elements.log, { type: "Markdown", props: { text: "```\nFAIL x\n```" } });
  assert.deepEqual(repaired.repairs.map((repair) => [repair.code, repair.path]), [["component_to_markdown", "body.elements.log"]]);
  const valid = await ask({ id: 2, op: "briefSection", section: section({ a: { type: "Markdown", props: { text: "A." } } }) });
  assert.deepEqual([valid.ok, valid.repairs], [true, []]);
  const refused = await ask({ id: 3, op: "briefSection", section: section({ f: { type: "Findings", props: { items: [{ id: "f1", severity: "low", text: "X." }] } } }) });
  assert.equal(refused.ok, false);
  assert.deepEqual(refused.problems.map((problem) => problem.code), ["missing_field"]);
  child.stdin.end();
  assert.equal(await new Promise((resolve) => child.on("exit", resolve)), 0);
});
