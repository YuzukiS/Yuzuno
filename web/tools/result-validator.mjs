// Generates runtimes/result-validator from the result contract (T-37):
//   validator.mjs  the contract's checks and zod in one plain ES module, run
//                  by Core with Node; it never imports web/src or node_modules
//   contract.json  the tool's name, schema version, limits, description and
//                  input schema, and the Project Brief's text and limits
//                  (`brief`, from brief-contract.ts), compiled into Core so its
//                  tool list needs no Node
//   THIRD_PARTY_NOTICES.txt  the npm packages validator.mjs bundles, with
//                  their licenses (third-party-notices.mjs)
// contract.json and the notices are committed; `--check` regenerates them in
// memory and fails if the committed files differ (CI runs it through
// result-validator.test.mjs). validator.mjs is not committed (YN-22): this
// writes it for tests, development and lab Cores, and the release build
// writes its own and compiles its SHA-256 into Core.
//
// contract.json writes a text of several lines as {"$lines": [...]}, one line
// per element, so two changes to different lines of a guide merge as text;
// contractJson.mjs reads it back, and Core joins the lines the same way.
// validator.mjs's second line names the contract.json it was generated with
// and the SHA-256 of everything after that line (validatorHeader), so Core
// and the release packager can tell a stale or edited bundle.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";
import { describeContract } from "../src/intelligent-ui/contract.ts";
import { describeBrief } from "../src/intelligent-ui/brief-contract.ts";
import { stringifyContract } from "./contract-json.mjs";
import { bundledFiles, bundledPackages, noticesText } from "./third-party-notices.mjs";

const web = fileURLToPath(new URL("..", import.meta.url));
export const outputDir = new URL("../../runtimes/result-validator/", import.meta.url);
/** The files `--check` compares with the committed ones. */
export const COMMITTED = ["contract.json", "THIRD_PARTY_NOTICES.txt"];

const sha256 = (text) => createHash("sha256").update(text).digest("hex");

/** validator.mjs's second line; Core and tools/package-release.py parse the same. */
export const validatorHeader = (contract, body) => `// yuzuno-result-validator contract=${sha256(contract)} body=${sha256(body)}`;

export async function generate() {
  const build = await rolldown({
    input: fileURLToPath(new URL("result-validator-entry.mjs", import.meta.url)),
    cwd: web,
    platform: "node",
    // Region comments name web-relative paths only, so the output is the
    // same in every checkout.
    logLevel: "silent",
  });
  let body, notices;
  try {
    const { output } = await build.generate({ format: "esm", codeSplitting: false, minify: true, comments: false });
    body = output[0].code;
    notices = noticesText("Third-party software in the Yuzuno result validator", [
      "validator.mjs, next to this file, contains code from the npm packages below:",
      "the packages of the modules web/tools/result-validator.mjs bundled into it.",
      "Each package keeps its own license. Where a package offers a choice of",
      "licenses, every text it ships is reproduced and no choice is made here.",
      "The rest of validator.mjs is Yuzuno's own code under the project license.",
    ], bundledPackages(bundledFiles(output, web)));
  } finally {
    await build.close();
  }
  const contract = stringifyContract({ ...describeContract(), brief: describeBrief() });
  const code = [
    "// Generated by web/tools/result-validator.mjs from web/src/intelligent-ui/contract.ts. Do not edit.",
    validatorHeader(contract, body),
    body,
  ].join("\n");
  return { "validator.mjs": code, "contract.json": contract, "THIRD_PARTY_NOTICES.txt": notices };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = await generate();
  const check = process.argv.includes("--check");
  let drift = false;
  for (const [name, content] of Object.entries(files)) {
    const target = new URL(name, outputDir);
    if (check) {
      if (!COMMITTED.includes(name)) continue;
      const committed = await readFile(target, "utf8").catch(() => null);
      if (committed !== content) {
        drift = true;
        console.error(`runtimes/result-validator/${name} is out of date; run: npm run build:result-validator`);
      }
    } else {
      await writeFile(target, content);
      console.log(`runtimes/result-validator/${name}: ${Buffer.byteLength(content)} bytes`);
    }
  }
  if (drift) process.exit(1);
}
