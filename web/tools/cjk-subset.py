#!/usr/bin/env python3
"""Build src/assets/fonts/yuzuno-han.woff2 and its fonts.css from Noto Sans SC.

The interface self-hosts a CJK subset because a font stack is a wish on a
machine with no Han coverage, and Yuzuno runs on those. This script is how
that file is made, so the asset can be rebuilt and checked rather than
trusted.

What it does, and why each step is there:

* It starts from the official Noto Sans SC variable font (CFF2, a `wght`
  axis of 100-900), downloaded from the Noto project and checked against a
  pinned SHA-256, so the source is a fact and not whatever was in a folder.
* It subsets to the code points in `cjk-codepoints.txt`, which is the
  coverage this interface ships. Changing coverage means changing that file,
  deliberately, in a commit that says so.
* It then *limits* the axis to 400-700 with 400 as the default, rather than
  instancing it away: the interface uses Regular through Bold, and the
  family's own default is Thin, which is not what unweighted text should be.
  `updateFontNames` makes the names say Regular, so a browser reporting the
  face reports what it is.
* The previous asset declared `font-weight: 400 700` while carrying no
  variation data at all (no CFF2 VarStore), so every weight drew the same
  outlines and Chinese never went bold. The check at the end fails the build
  if that happens again: an asset that promises weights it cannot draw is
  worse than one that promises nothing.

Needs fontTools and brotli:

    python3 -m venv .venv && .venv/bin/pip install 'fonttools[woff]' brotli
    .venv/bin/python tools/cjk-subset.py            # from web/

`--source <file>` uses a font already on disk (its digest is still checked).
`--allow-source <sha256>` builds from another revision of the source on
purpose, and records it in the generated CSS.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

# Pinned to a commit, not to `main`: a branch moves, and then the digest
# below would only tell you that it moved, not get you the file it names.
SOURCE_COMMIT = "165c01b46ea533872e002e0785ff17e44f6d97d8"
SOURCE_PATH = "Sans/Variable/OTF/Subset/NotoSansSC-VF.otf"
SOURCE_URL = f"https://raw.githubusercontent.com/notofonts/noto-cjk/{SOURCE_COMMIT}/{SOURCE_PATH}"
SOURCE_SHA256 = "d13ed01ec8aa45d6178999b648e96fb92150683e9f8e2a581f2acf208dcbe44b"
# What the interface uses: Regular through Bold, with Regular the default.
AXIS_MIN, AXIS_DEFAULT, AXIS_MAX = 400, 400, 700

HERE = Path(__file__).resolve().parent
FONT_DIR = HERE.parent / "src" / "assets" / "fonts"
CODEPOINTS = HERE / "cjk-codepoints.txt"
OUT_FONT = FONT_DIR / "yuzuno-han.woff2"
OUT_CSS = FONT_DIR / "fonts.css"
SAMPLE = "加粗的中文字体"


def read_codepoints() -> list[int]:
    points = []
    for line in CODEPOINTS.read_text().splitlines():
        line = line.split("#")[0].strip()
        if line:
            points.append(int(line.removeprefix("U+"), 16))
    if not points:
        sys.exit(f"{CODEPOINTS} lists no code points")
    return sorted(set(points))


def fetch_source(given: Path | None, allowed: str) -> tuple[Path, str]:
    if given:
        data = given.read_bytes()
    else:
        print(f"reading {SOURCE_URL}")
        with urllib.request.urlopen(SOURCE_URL) as response:  # noqa: S310 - pinned, checked below
            data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != allowed:
        sys.exit(
            f"the source font is not the pinned one\n  expected {allowed}\n  found    {digest}\n"
            "Pass --allow-source <sha256> to build from another revision on purpose."
        )
    path = Path(tempfile.mkdtemp(prefix="cjk-subset-")) / "source.otf"
    path.write_bytes(data)
    return path, digest


def ranges(points: list[int]) -> list[tuple[int, int]]:
    spans: list[tuple[int, int]] = []
    for point in points:
        if spans and point == spans[-1][1] + 1:
            spans[-1] = (spans[-1][0], point)
        else:
            spans.append((point, point))
    return spans


def _version(package: str) -> str:
    try:
        from importlib.metadata import version

        return version(package)
    except Exception:
        return "unknown"


def css(digest: str, points: list[int]) -> str:
    spans = ", ".join(f"U+{lo:04X}" + (f"-{hi:04X}" if hi != lo else "") for lo, hi in ranges(points))
    wrapped: list[str] = []
    line = "   "
    for piece in spans.split(", "):
        if len(line) + len(piece) + 2 > 78:
            wrapped.append(line.rstrip())
            line = "   "
        line += f" {piece},"
    wrapped.append(line.rstrip().rstrip(","))
    body = "\n".join(wrapped)
    return f"""/* Generated by tools/cjk-subset.py — do not edit.
 *
 * Noto Sans SC, subset to {len(points)} CJK code points and limited to the
 * weights this interface uses ({AXIS_MIN}-{AXIS_MAX}, default {AXIS_DEFAULT}). Self-hosted because a
 * font stack is a wish on a machine with no Han coverage, and Yuzuno runs on
 * those.
 *
 * It keeps its weight axis: the outlines really do change with font-weight,
 * which `tools/cjk-subset.py` checks before writing this file.
 *
 * The unicode-range is the point: an English session never asks for a
 * code point in it, so this file is never fetched.
 *
 * Source: {SOURCE_URL}
 * SHA-256: {digest}
 * Built with fontTools {_version("fontTools")}, brotli {_version("brotli")}. Another
 * version may produce different bytes; what is promised is the check above,
 * not a byte-identical rebuild.
 *
 * Noto Sans SC is licensed under the SIL Open Font License 1.1 —
 * see LICENSE-NotoSansSC.txt beside this file.
 */
@font-face {{
  font-family: "Yuzuno Han";
  font-style: normal;
  font-weight: {AXIS_MIN} {AXIS_MAX};
  font-display: swap;
  src: url("./yuzuno-han.woff2") format("woff2-variations");
  unicode-range:
{body};
}}
"""


def replace_whole(path: Path, data: bytes) -> None:
    """Put `data` at `path` in one step, or leave what was there.

    `write_bytes` truncates the file first, so an interrupted write would
    leave the asset shorter than it was. The temporary file is made beside
    the target, which keeps it on the same filesystem, where `os.replace` is
    atomic.
    """
    temporary = path.with_name(f".{path.name}.new")
    try:
        temporary.write_bytes(data)
        os.replace(temporary, path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def verify(path: Path, points: list[int]) -> None:
    """Refuse a built font that does not do what its CSS will promise.

    Everything here is read back from `path`, the bytes that would ship.
    """
    from fontTools.pens.areaPen import AreaPen
    from fontTools.ttLib import TTFont
    from fontTools.varLib import instancer

    font = TTFont(path)
    if "fvar" not in font:
        sys.exit(f"{path.name} has no weight axis at all")
    axis = next((a for a in font["fvar"].axes if a.axisTag == "wght"), None)
    if axis is None:
        sys.exit(f"{path.name} has no wght axis")
    if (axis.minValue, axis.defaultValue, axis.maxValue) != (AXIS_MIN, AXIS_DEFAULT, AXIS_MAX):
        sys.exit(f"{path.name} has wght {axis.minValue}-{axis.maxValue} default {axis.defaultValue}, not {AXIS_MIN}-{AXIS_MAX} default {AXIS_DEFAULT}")
    if "CFF2" not in font:
        sys.exit(f"{path.name} has no CFF2 outlines")
    if not hasattr(font["CFF2"].cff.topDictIndex[0], "VarStore"):
        sys.exit(
            f"{path.name} carries no variation data (CFF2 has no VarStore), so every weight would draw "
            "the same outlines — this is the defect this script exists to prevent"
        )

    shipped = set(font.getBestCmap())
    if shipped != set(points):
        missing, extra = len(set(points) - shipped), len(shipped - set(points))
        sys.exit(f"{path.name} covers {len(shipped)} code points, not the {len(points)} asked for ({missing} missing, {extra} unexpected)")

    # Instancing the shipped bytes is itself the test: the broken asset this
    # replaced raised AttributeError here.
    try:
        light = instancer.instantiateVariableFont(TTFont(path), {"wght": AXIS_MIN}, inplace=False)
        heavy = instancer.instantiateVariableFont(TTFont(path), {"wght": AXIS_MAX}, inplace=False)
    except Exception as error:
        sys.exit(f"{path.name} cannot be instanced at {AXIS_MIN} and {AXIS_MAX} — {type(error).__name__}: {error}")

    cmap = light.getBestCmap()
    absent = [char for char in SAMPLE if ord(char) not in cmap]
    if absent:
        sys.exit(f"{path.name} is missing the characters this check reads: {''.join(absent)}")

    flat = []
    for char in SAMPLE:
        name = cmap[ord(char)]
        areas = []
        for built in (light, heavy):
            pen = AreaPen(built.getGlyphSet())
            built.getGlyphSet()[name].draw(pen)
            areas.append(abs(pen.value))
        if areas[0] >= areas[1] * 0.98:
            flat.append(f"{char}: {areas[0]:.0f} at {AXIS_MIN} vs {areas[1]:.0f} at {AXIS_MAX}")
    if flat:
        sys.exit("these outlines barely change with weight, so this font would promise a bold it cannot draw:\n  " + "\n  ".join(flat))
    print(f"checked {path.name}: wght {AXIS_MIN}-{AXIS_MAX} default {AXIS_DEFAULT}, {len(shipped)} code points, outlines change with weight")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="a copy of the source font already on disk")
    parser.add_argument("--allow-source", default=SOURCE_SHA256, help="build from this source digest")
    args = parser.parse_args()

    try:
        from fontTools.pens.areaPen import AreaPen
        from fontTools.ttLib import TTFont
        from fontTools.varLib import instancer
    except ImportError:
        sys.exit("fontTools is needed: python3 -m venv .venv && .venv/bin/pip install 'fonttools[woff]' brotli")

    points = read_codepoints()
    source, digest = fetch_source(args.source, args.allow_source)
    work = source.parent

    listing = work / "codepoints.txt"
    listing.write_text("\n".join(f"U+{point:04X}" for point in points) + "\n")
    subset = work / "subset.otf"
    print(f"subsetting {len(points)} code points")
    subsetting = subprocess.run(
        [sys.executable, "-m", "fontTools.subset", str(source), f"--unicodes-file={listing}",
         f"--output-file={subset}", "--layout-features=*", "--no-hinting", "--desubroutinize"],
        capture_output=True,
        text=True,
    )
    if subsetting.returncode != 0:
        detail = (subsetting.stderr or subsetting.stdout).strip().splitlines()
        sys.exit(
            "the source font could not be subset, so nothing was written.\n  "
            + "\n  ".join(detail[-3:] or ["fontTools.subset gave no reason"])
        )

    font = TTFont(subset)
    print(f"limiting wght to {AXIS_MIN}-{AXIS_MAX}, default {AXIS_DEFAULT}")
    instancer.instantiateVariableFont(
        font, {"wght": (AXIS_MIN, AXIS_DEFAULT, AXIS_MAX)}, inplace=True, updateFontNames=True
    )

    # Write what would ship, then check *that file*, read back from disk.
    # Checking the font in memory, or the subset before its axis was limited,
    # would miss exactly the failure this asset already had once: variation
    # data lost while limiting or serialising, leaving a font that promises
    # weights it cannot draw.
    candidate = work / "candidate.woff2"
    font.flavor = "woff2"
    font.save(candidate)
    verify(candidate, points)

    # Each file is swapped in whole, through a temporary file beside it and
    # os.replace, so an interruption cannot leave a half-written font where a
    # font used to be. The two swaps are not one transaction: stopping
    # between them leaves the new font with the previous CSS, which differs
    # only in its header, since the code points are the same file's input.
    replace_whole(OUT_FONT, candidate.read_bytes())
    replace_whole(OUT_CSS, css(digest, points).encode())
    print(f"wrote {OUT_FONT} ({OUT_FONT.stat().st_size:,} bytes) and {OUT_CSS.name}")


if __name__ == "__main__":
    main()
