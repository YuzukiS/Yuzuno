#!/usr/bin/env python3
"""Copy the Job input guard's rule source into the two scripts that run it
(YN-207).

core/src/jobs/guard_rules.py is the only hand-edited copy. The region between
its two marker lines is copied verbatim into host.py and into COMMON in
remote_job.py, between the same markers. `--check` compares and writes
nothing; without it the copies are rewritten. Either way the same problems
are refused: a missing or repeated marker, a region that would close COMMON's
string, or a region whose copies cannot compile.

Run from anywhere:
    python3 scripts/sync_guard_rules.py --check
"""
import argparse
import ast
import io
import sys
from pathlib import Path

START = '# >>> guard rules (source: core/src/jobs/guard_rules.py; generated by scripts/sync_guard_rules.py) >>>'
END = '# <<< guard rules <<<'
ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path('core/src/jobs/guard_rules.py')
TARGETS = (Path('core/src/jobs/host.py'), Path('core/src/jobs/remote_job.py'))
# The string COMMON is assigned to in remote_job.py: the region lives inside it.
COMMON_NAME = 'COMMON'


class Problem(Exception):
    """A file the tool will not sync, and why."""


def read(path):
    with io.open(str(path), encoding='utf-8', newline='') as stream:
        return stream.read()


def write(path, text):
    with io.open(str(path), 'w', encoding='utf-8', newline='') as stream:
        stream.write(text)


def locate(text, name):
    """(the lines before the start marker, the region, the lines from the end
    marker on). The region includes its final newline, or is empty."""
    lines = text.split('\n')
    starts = [number for number, line in enumerate(lines) if line == START]
    ends = [number for number, line in enumerate(lines) if line == END]
    if not starts:
        raise Problem('%s: the start marker is missing' % name)
    if not ends:
        raise Problem('%s: the end marker is missing' % name)
    if len(starts) > 1 or len(ends) > 1:
        raise Problem('%s: the %s marker appears %d times' % (name, 'start' if len(starts) > 1 else 'end',
                                                                 max(len(starts), len(ends))))
    if starts[0] > ends[0]:
        raise Problem('%s: the end marker comes before the start marker' % name)
    body = '\n'.join(lines[starts[0] + 1:ends[0]])
    return lines[:starts[0] + 1], body + '\n' if body else '', lines[ends[0]:]


def check_region(body, name):
    """The region as it must be to live in host.py and inside COMMON's r'''...'''
    string, and to be worth copying."""
    if not body:
        raise Problem('%s: the region is empty' % name)
    if not body.endswith('\n'):
        raise Problem('%s: the region does not end with a newline' % name)
    if body.endswith('\n\n'):
        raise Problem('%s: the region ends with a blank line' % name)
    if "'''" in body:
        raise Problem("%s: the region contains ''' and would close COMMON's string" % name)
    for number, line in enumerate(body.split('\n'), 1):
        if line != line.rstrip():
            raise Problem('%s: line %d of the region ends in whitespace' % (name, number))
    try:
        compile(body, name, 'exec')
    except SyntaxError as error:
        raise Problem('%s: the region does not parse (line %s: %s)' % (name, error.lineno, error.msg))
    return body


def region(path, name=None):
    """The region text of one file, checked for copying."""
    return check_region(locate(read(path), name or str(path))[1], name or str(path))


def replace(path, body):
    text = read(path)
    before, found, after = locate(text, str(path))
    if found == body:
        return False
    replacement = '\n'.join(before + body.split('\n')[:-1] + after)
    check_structure(str(path), replacement)
    write(path, replacement)
    return True


def check_structure(name, text):
    """The file still parses, and the region is still inside the string it is
    meant to be in. An unparsable result is never written."""
    try:
        compile(text, name, 'exec')
    except SyntaxError as error:
        raise Problem('%s: the result does not parse (line %s: %s)' % (name, error.lineno, error.msg))
    if name.endswith('remote_job.py'):
        common = None
        for node in ast.parse(text).body:
            if (isinstance(node, ast.Assign) and len(node.targets) == 1
                    and isinstance(node.targets[0], ast.Name) and node.targets[0].id == COMMON_NAME):
                common = node.value
        if common is None:
            raise Problem('%s: %s is no longer assigned' % (name, COMMON_NAME))
        try:
            value = ast.literal_eval(common)
        except ValueError:
            raise Problem('%s: %s is no longer a plain string' % (name, COMMON_NAME))
        if not isinstance(value, str):
            raise Problem('%s: %s is not a string' % (name, COMMON_NAME))
        supervisor = None
        for node in ast.parse(text).body:
            if (isinstance(node, ast.Assign) and len(node.targets) == 1
                    and isinstance(node.targets[0], ast.Name) and node.targets[0].id == 'SUPERVISOR'):
                try:
                    supervisor = ast.literal_eval(node.value)
                except ValueError:
                    supervisor = None
        if not isinstance(supervisor, str):
            raise Problem('%s: SUPERVISOR is no longer a plain string' % name)
        compile(value + supervisor, name + ' (COMMON + SUPERVISOR)', 'exec')


def check(root=None):
    """Problems found, as text lines; empty when every copy is the source."""
    root = Path(root) if root is not None else ROOT
    source = root / SOURCE
    body = region(source, str(SOURCE))
    problems = []
    for target in TARGETS:
        try:
            copied = region(root / target, str(target))
        except Problem as error:
            problems.append(str(error))
            continue
        if copied != body:
            problems.append('%s: its region differs from %s; run scripts/sync_guard_rules.py' % (target, SOURCE))
    return problems


def sync(root=None):
    """Rewrite every target from the source. (changed paths, problems)."""
    root = Path(root) if root is not None else ROOT
    body = region(root / SOURCE, str(SOURCE))
    changed, problems = [], []
    for target in TARGETS:
        try:
            if replace(root / target, body):
                changed.append(str(target))
        except Problem as error:
            problems.append(str(error))
    return changed, problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='compare the copies, write nothing')
    parser.add_argument('--root', default=None, help='repository root (default: this checkout)')
    options = parser.parse_args(argv)
    try:
        if options.check:
            problems = check(options.root)
            for problem in problems:
                print(problem, file=sys.stderr)
            if problems:
                return 1
            print('guard rules: %s and its copies in %s are in sync' % (SOURCE, ', '.join(str(t) for t in TARGETS)))
            return 0
        changed, problems = sync(options.root)
    except Problem as error:
        print(str(error), file=sys.stderr)
        return 1
    for problem in problems:
        print(problem, file=sys.stderr)
    for path in changed:
        print('updated %s' % path)
    if problems:
        return 1
    if not changed:
        print('guard rules: every copy is already the source')
    return 0


if __name__ == '__main__':
    sys.exit(main())
