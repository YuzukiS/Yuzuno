"""The Job input guard's rules, without I/O (YN-207).

The rules a local Job (host.py) and a Job on another machine (remote_job.py)
must answer the same way: the bounds, the one refusal, which Git and file
facts count as a change, the order a change is named in, and the words of a
refusal. Each end still reads its own facts; this module never opens a file,
runs a command, talks to systemd or SSH, or writes a Job's state.

This file is the only hand-edited copy. The marked region below is copied
verbatim into host.py and into COMMON in remote_job.py by
scripts/sync_guard_rules.py; `--check` (run by scripts/test_guard_rules_sync.py
and by CI) fails when a copy drifts, a marker is missing or repeated, or the
region could no longer live inside COMMON's string.

Python 3.6: a machine's python3 may be that old. No walrus, no f-string
debugging, no capture_output.
"""
